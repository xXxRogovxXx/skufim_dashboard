def _load_ru_cities():
    """name → [lon, lat] из справочника; subject_key → координаты админцентра."""
    path = os.path.join(os.path.dirname(__file__), "data", "ru_cities.json")
    coords, subj_best = {}, {}
    try:
        with open(path, encoding="utf-8") as f:
            cities = json.load(f)
    except Exception:
        return coords, {}
    for c in cities:
        try:
            lon = float(c["coords"]["lon"]); lat = float(c["coords"]["lat"])
        except (KeyError, TypeError, ValueError):
            continue
        name = str(c.get("name", "")).strip()
        pop = int(c.get("population") or 0)
        if name and (name not in coords or pop > coords.get(name, (0,))[0]):
            coords[name] = (pop, lon, lat)
        subj = _region_key(c.get("subject", ""))
        if subj and (subj not in subj_best or pop > subj_best[subj][0]):
            subj_best[subj] = (pop, lon, lat)
    # оставляем только [lon,lat]
    coords = {n: [v[1], v[2]] for n, v in coords.items()}
    subj_coords = {s: [v[1], v[2]] for s, v in subj_best.items()}
    return coords, subj_coords


def _region_key(s):
    """Нормализует название региона/subject в компактный ключ (без пробелов/дефисов)."""
    s = str(s).lower().replace("ё", "е")
    s = re.sub(r"[()—–]|кузбасс|югра|г\.", " ", s)
    s = re.sub(r"\b(область|области|край|края|республика|автономный|округ|ао)\b", " ", s)
    return re.sub(r"[\s\-]+", "", s).strip()  # убираем пробелы и дефисы → компактно


# Строим объединённый справочник координат
_RU_CITIES, _SUBJECT_COORDS = _load_ru_cities()
CITY_COORDS = {**_RU_CITIES, **_CURATED}  # кураторские значения имеют приоритет


def normalize_city(name):
    if name is None:
        return "Не определен"
    s = str(name).strip()
    return ALIASES.get(s, s)


def city_coords(name):
    """[lon, lat] для города / региона / округа / страны. None — если совсем не нашли."""
    if name is None:
        return None
    norm = normalize_city(name)
    # 1. прямой город
    if norm in CITY_COORDS:
        return CITY_COORDS[norm]
    low = norm.lower().replace("ё", "е")
    # 2. федеральный округ
    if "федеральн" in low:
        for kw, city in _FEDERAL.items():
            if kw in low:
                return CITY_COORDS.get(city)
        return None
    # 3. страна
    if low in _COUNTRY:
        return CITY_COORDS.get(_COUNTRY[low])
    # 4. область СНГ (Беларусь/Украина/Казахстан)
    rk = _region_key(norm)
    if rk in _CIS_OBL:
        return CITY_COORDS.get(_CIS_OBL[rk])
    # 5. регион РФ (область/край/республика/АО) → админцентр subject
    if re.search(r"област|кра[йя]|республик|автономн|\bао\b|округ", low):
        rk = _REGION_ALIASES.get(rk, rk)  # адъективные/иные формы → subject
        if rk in _SUBJECT_COORDS:
            return _SUBJECT_COORDS[rk]
    return None
