def normalize_city(name):
    """Каноничное имя города (сводит дубли). None → 'Не определен'."""
    if name is None:
        return "Не определен"
    s = str(name).strip()
    return ALIASES.get(s, s)


def city_coords(name):
    """[lon, lat] или None, если это регион/страна/неизвестный город."""
    return CITY_COORDS.get(normalize_city(name))
